// 6 年生の「電気の利用」に合わせて、くわしい数字は出さない

export interface Step {
  title: string;
  /** ハカセの説明。改行で段落を分ける */
  text: string;
  /** 光らせる部品 (図の data-part) */
  parts: string[];
  /** 動かす流れ (図の data-flow) */
  flows: string[];
}

export interface Control {
  label: string;
  min: number;
  max: number;
  step: number;
  /** はじめの値 */
  value: number;
  /** つまみの値の書き方 */
  show: (v: number) => string;
}

export interface Plant {
  id: PlantId;
  name: string;
  /** 一覧のカードに書く、ひとことの説明 */
  lead: string;
  steps: Step[];
  control: Control;
  /** つまみの値 → 発電量 (0〜1) */
  output: (v: number) => number;
  /** つまみの値 → 図の CSS の変数 (制御棒の位置・パネルの向き) */
  vars?: (v: number) => Record<string, string>;
  /** エネルギーの変わり方 (はじめに の解説にはない) */
  energy?: string[];
  /** くらべてみようの表 */
  compare?: { fuel: string; co2: string; weather: string };
  merits: string[];
  issues: string[];
  /** たしかめ問題 (今日の10問の 6 年生むけにも出す) */
  quiz: Fact[];
}


const upperCalorie: Gen = {
  id: 'heat-u-calorie',
  make: (rng) =>
    pick(rng, [
      () => {
        const g = pick(rng, [50, 100, 200, 300, 500]);
        const from = pick(rng, [10, 15, 20, 25]);
        const up = pick(rng, [5, 10, 20, 30, 40]);
        return numeric(rng, {
          text: `水1gの温度を1℃上げるのに必要な熱の量を1カロリーといいます。${from}℃の水${g}gを${from + up}℃にするには、何カロリーの熱が必要ですか。`,
          correct: g * up,
          wrong: [g * (from + up), g * from, g + up, g * up * 2, (g * up) / 2],
          unit: 'カロリー',
          explanation: `必要な熱の量（カロリー）＝ 水の重さ（g）× 上がった温度（℃）です。上がった温度は ${from + up} − ${from} ＝ ${up}℃ なので、${g} × ${up} ＝ ${g * up}（カロリー）です。`,
        });
      },
      () => {
        const rise = pick(rng, [12, 16, 20, 24]);
        const k = pick(rng, [2, 4]);
        return numeric(rng, {
          text: `水100gをガスバーナーで5分間あたためると、温度が${rise}℃上がりました。同じ強さのほのおで、水${100 * k}gを5分間あたためると、温度は何℃上がりますか。熱は、すべて水の温度を上げるのに使われるものとします。`,
          correct: rise / k,
          wrong: [rise, rise * k, rise / k + 2, rise - k, rise / (k * 2)],
          unit: '℃',
          explanation: `同じ量の熱を加えたとき、上がる温度は水の重さに反比例します。水が${k}倍になると、上がる温度は${k}分の1になるので、${rise} ÷ ${k} ＝ ${rise / k}（℃）です。`,
        });
      },
      () => {
        const rise = pick(rng, [8, 10, 12, 15]);
        const k = pick(rng, [2, 3]);
        return numeric(rng, {
          text: `水200gをガスバーナーで4分間あたためると、温度が${rise}℃上がりました。同じ強さのほのおで、同じ量の水を${4 * k}分間あたためると、温度は何℃上がりますか。水はふっとうしないものとします。`,
          correct: rise * k,
          wrong: [rise, rise + k, rise * (k + 1), (rise * k) / 2, rise * k + 4],
          unit: '℃',
          explanation: `同じ量の水では、上がる温度はあたためた時間に比例します。時間が${k}倍なので、${rise} × ${k} ＝ ${rise * k}（℃）です。`,
        });
      },
    ])(),
};


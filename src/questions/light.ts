const upperWave: Gen = {
  id: 'light-u-wave',
  make: (rng) => {
    const v = pick(rng, [
      { q: 'いちばん高い音', key: 'waves', max: true, ex: '高い音ほど、同じ時間にふるえる回数（しん動数）が多く、波の数が多くなります。' },
      { q: 'いちばん低い音', key: 'waves', max: false, ex: '低い音ほど、同じ時間にふるえる回数（しん動数）が少なく、波の数が少なくなります。' },
      { q: 'いちばん大きい音', key: 'amp', max: true, ex: '大きい音ほど、ふれはば（しんぷく）が大きく、波の高さが高くなります。' },
      { q: 'いちばん小さい音', key: 'amp', max: false, ex: '小さい音ほど、ふれはば（しんぷく）が小さく、波の高さが低くなります。' },
    ] as const);
    for (;;) {
      const list = Array.from({ length: 4 }, () => ({ amp: pick(rng, [1, 2, 3]), waves: pick(rng, [2, 3, 4, 5, 6]) }));
      const values = list.map((p) => p[v.key]);
      const target = v.max ? Math.max(...values) : Math.min(...values);
      if (values.filter((x) => x === target).length !== 1) continue;
      if (new Set(list.map((p) => `${p.amp}:${p.waves}`)).size !== 4) continue;
      const answer = KANA[values.indexOf(target)];
      return fixed({
        text: `図は、4つの音をマイクで拾い、オシロスコープで波の形として表したものです。横は時間、たてはふれはばを表し、目もりはどれも同じです。${v.q}は、ア〜エのどれですか。`,
        svg: waveGrid(list, KANA.slice(0, 4)),
        choices: KANA.slice(0, 4),
        correct: answer,
        explanation: `答えは ${answer} です。${v.ex}音の高さは波の数で、音の大きさは波の高さでわかります。`,
      });
    }
  },
};


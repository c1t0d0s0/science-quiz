const SENSES = [
  { what: '明るさや色、形', where: '目' },
  { what: '音', where: '耳' },
  { what: 'におい', where: '鼻' },
  { what: 'あまい・からいなどの味', where: 'した' },
  { what: '手ざわりや、あたたかさ・つめたさ', where: '皮ふ' },
];

const lowerSenses: Gen = {
  id: 'body-l-senses',
  make: (rng) => {
    const s = pick(rng, SENSES);
    return choice(rng, {
      text: `「${s.what}」を感じとるのは、からだのどこですか。`,
      correct: s.where,
      wrong: SENSES.map((x) => x.where),
      explanation: `${s.what}は${s.where}で感じとります。目・耳・鼻・した・皮ふで感じたことは、脳に伝わります。`,
    });
  },
};


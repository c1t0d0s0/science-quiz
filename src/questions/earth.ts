const upperDisaster: Gen = {
  id: 'earth-u-disaster',
  make: (rng) => {
    if (rng() < 0.35) {
      // 緊急地震速報: P 波で地震を見つけ、S 波 (大きなゆれ) がとどく前に知らせる
      const [p, s] = pick(rng, [[6, 3], [8, 4]]);
      const t = pick(rng, [4, 5, 6, 8]);
      const arrive = t + pick(rng, [4, 6, 10, 12, 20]);
      const d = arrive * s;
      const left = arrive - t;
      return numeric(rng, {
        text: `ある地震で、P波は秒速${p}km、S波（大きなゆれを伝える波）は秒速${s}kmで伝わりました。地震が起こってから${t}秒後に、緊急地震速報が出されました。しん源から${d}kmはなれた地点では、速報が出てから何秒後に大きなゆれがとどきますか。`,
        correct: left,
        wrong: [arrive, d / p, arrive + t, arrive - d / p, left * 2],
        unit: '秒',
        explanation: `S波がとどくのは、地震が起こってから ${d} ÷ ${s} ＝ ${arrive}秒後です。速報は${t}秒後に出ているので、${arrive} − ${t} ＝ ${left}（秒後）です。緊急地震速報は、先にとどくP波をとらえて、大きなゆれ（S波）が来る前に知らせるしくみです。`,
      });
    }
    const f = pick(rng, DISASTER_FACTS);
    return choice(rng, { text: f.q, correct: f.a, wrong: f.wrong, explanation: f.ex });
  },
};


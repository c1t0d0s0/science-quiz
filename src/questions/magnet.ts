const upperStrength: Gen = {
  id: 'magnet-u-strength',
  make: (rng) => {
    // 電磁石の強さは、コイルのまき数と、流れる電流 (直列につないだ乾電池の数) が大きいほど強い
    const strongest = rng() < 0.6;
    for (;;) {
      const list = shuffle(
        [50, 100, 150, 200].flatMap((turns) => [1, 2, 3].map((cells) => ({ turns, cells }))),
        rng,
      ).slice(0, 4);
      const values = list.map((p) => p.turns * p.cells);
      const target = strongest ? Math.max(...values) : Math.min(...values);
      if (values.filter((v) => v === target).length !== 1) continue;
      // まき数も電池の数も、ほかのどれにも負けていない (または勝っていない) ものだけを答えにする
      const best = list[values.indexOf(target)];
      const clear = list.every((p) => p === best || (strongest ? p.turns <= best.turns && p.cells <= best.cells : p.turns >= best.turns && p.cells >= best.cells));
      if (!clear) continue;
      return fixed({
        text: `図のア〜エのように、同じ鉄のしんに同じ導線をまいて電磁石をつくり、乾電池につなぎました。導線全体の長さはどれも同じで、乾電池を2個以上使うときは直列つなぎにします。電磁石のはたらきがいちばん${strongest ? '強い' : '弱い'}ものはどれですか。`,
        svg: coilGrid(list, KANA.slice(0, 4)),
        choices: KANA.slice(0, 4),
        correct: KANA[list.indexOf(best)],
        explanation: `電磁石は、コイルのまき数が多いほど、また、流れる電流が大きいほど強くなります。乾電池を直列つなぎでふやすと、電流が大きくなります。${KANA[list.indexOf(best)]} は ${best.turns}回まきで乾電池${best.cells}個なので、いちばん${strongest ? '強く' : '弱く'}なります。`,
      });
    }
  },
};

const upperCompare: Gen = {
  id: 'magnet-u-compare',
  make: (rng) => {
    // 4 つの電磁石を、ア〜エにばらばらに割りふる
    const setups = shuffle(
      [
        { turns: 100, cells: 1 },
        { turns: 200, cells: 1 },
        { turns: 100, cells: 2 },
        { turns: 200, cells: 2 },
      ],
      rng,
    );
    const pairs: [number, number][] = [[0, 1], [0, 2], [0, 3], [1, 2], [1, 3], [2, 3]];
    const name = ([a, b]: [number, number]) => `${KANA[a]}と${KANA[b]}`;
    const byTurns = pairs.filter(([a, b]) => setups[a].cells === setups[b].cells);
    const byCells = pairs.filter(([a, b]) => setups[a].turns === setups[b].turns);
    const both = pairs.filter(([a, b]) => setups[a].cells !== setups[b].cells && setups[a].turns !== setups[b].turns);
    const turns = rng() < 0.5;
    const correct = pick(rng, turns ? byTurns : byCells);
    // 正しい組み合わせは 2 つあるので、選択肢には 1 つだけ入れる
    const choices = [correct, ...(turns ? byCells : byTurns), pick(rng, both)].sort((x, y) => x[0] - y[0] || x[1] - y[1]);
    return fixed({
      text:
        `「${turns ? 'コイルのまき数' : '流れる電流の大きさ'}」と電磁石の強さの関係を調べます。次のア〜エのうち、どれとどれをくらべればよいですか。導線全体の長さは、どれも同じです。\n` +
        setups.map((p, k) => `${KANA[k]}：${p.turns}回まき・乾電池${p.cells}個${p.cells > 1 ? '（直列）' : ''}`).join('\n'),
      choices: choices.map(name),
      correct: name(correct),
      explanation: `調べたい条件を1つだけ変え、ほかの条件は同じにしてくらべます。${name(correct)}は、${turns ? '乾電池の数が同じで、まき数だけ' : 'まき数が同じで、乾電池の数だけ'}がちがいます。`,
    });
  },
};


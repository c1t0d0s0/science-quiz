const TERMS = new Map(GLOSSARY);
// すでにふりがなのついている言葉 (うしろが「(」) や、ほかの漢字につづく言葉には手を入れない
const PATTERN = new RegExp(`(?<![一-龠々])(${GLOSSARY.map(([term]) => term).join('|')})(?![一-龠々(])`, 'g');

/** 文の中の言葉に「漢字(かんじ)」の形でふりがなをつける。同じ言葉には、最初の 1 回だけつける */
export function addRuby(text: string): string {
  const seen = new Set<string>();
  return text.replace(PATTERN, (term) => {
    if (seen.has(term)) return term;
    seen.add(term);
    return TERMS.get(term)!;
  });
}
